void main(){
  //* Arithmetic Operators
  int a = 10;
  int b = 5;
  // Addition
  int sum = a + b;
  print("Addition: $sum");

  // Subtraction
  int difference = a - b;
  print("Subtraction: $difference");

  // Multiplication
  int product = a * b;
  print("Multiplication: $product");

  // Division
  double quotient = a / b;
  print("Division: $quotient");

  // Integer Division
  int intQuotient = a ~/ b;
  print("Integer Division: $intQuotient");

  // Modulus
  int remainder = a % b;
  print("Modulus: $remainder");
}