void main(){
  //* Equality & Relational Operators
  int a = 10;
  int b = 5;

  // Equality
  bool isEqual = a == b;
  print("Is Equal: $isEqual");

  // Inequality
  bool isNotEqual = a != b;
  print("Is Not Equal: $isNotEqual");

  // Greater Than
  bool isGreaterThan = a > b;
  print("Is Greater Than: $isGreaterThan");

  // Less Than
  bool isLessThan = a < b;
  print("Is Less Than: $isLessThan");

  // Greater Than or Equal To
  bool isGreaterThanOrEqualTo = a >= b;
  print("Is Greater Than or Equal To: $isGreaterThanOrEqualTo");

  // Less Than or Equal To
  bool isLessThanOrEqualTo = a <= b;
  print("Is Less Than or Equal To: $isLessThanOrEqualTo");
}