void main(){
    int a = 10;
    int b = 5;
    double c = 20.0;
    
    //* Addition assignment
    a += b; //* a = a + b
    print("Addition Assignment: $a");

    //* Subtraction assignment
    a -= b; //* a = a - b
    print("Subtraction Assignment: $a");

    //* Multiplication assignment
    a *= b; //* a = a * b
    print("Multiplication Assignment: $a");

    //* Division assignment
    c /= a; //* c = c / a
    print("Division Assignment: $c");

    //* Integer Division assignment
    a ~/= b; //* a = a ~/ b
    print("Integer Division Assignment: $a");

    //* Modulus assignment
    a %= b; //* a = a % b
    print("Modulus Assignment: $a");


}