void main(){
  //* Anonymous function
  var add = (int a, int b) {
    return a + b;
  };
  print(add(5, 3)); // Output: 8

  //* Using an anonymous function as a callback
  List<int> numbers = [1, 2, 3, 4, 5];
 numbers.forEach((number) {
    print(number * 2); // Output: 2, 4, 6, 8, 10
  });

  var prices = [10, 20, 30];
  prices.forEach((price) {
    var newPrice = price + 5;
    print("newPrice: $newPrice"); // Output: 15, 25, 35
  });

/*
  উপরের উদাহরণে, আমরা Anonymous Function ব্যবহার করেছি।
  Anonymous Function হলো এমন একটি ফাংশন, যার নিজস্ব
  কোনো নাম থাকে না।

  প্রথমে, add নামের একটি ভেরিয়েবলে একটি নামবিহীন
  ফাংশন রাখা হয়েছে। এই ফাংশনটি a এবং b নামে দুটি
  সংখ্যা গ্রহণ করে এবং তাদের যোগফল return করে।

  যখন add(5, 3) কল করা হয়, তখন যোগফল 8 দেখানো হয়।

  দ্বিতীয়ত, numbers নামের একটি List তৈরি করা হয়েছে,
  যেখানে 1 থেকে 5 পর্যন্ত সংখ্যা রয়েছে।
  forEach() ব্যবহার করে List-এর প্রতিটি সংখ্যার ওপর
  একটি করে কাজ করা হয়েছে।

  এখানে প্রতিটি সংখ্যাকে 2 দিয়ে গুণ করে ফলাফল দেখানো হয়।
  যেমন, 1-এর জন্য 2, 2-এর জন্য 4 এবং এভাবে চলতে থাকে।

  তৃতীয়ত, prices নামের একটি List-এ 10, 20 ও 30 রাখা হয়েছে।
  forEach() ব্যবহার করে প্রতিটি দামের সঙ্গে 5 যোগ করা হয়েছে।
  এরপর নতুন দামটি newPrice ভেরিয়েবলে রেখে দেখানো হয়েছে।

  সংক্ষেপে:
  - Anonymous Function: যে ফাংশনের নিজস্ব কোনো নাম নেই।
  - var add: নামবিহীন ফাংশনটি add ভেরিয়েবলে রাখা হয়েছে।
  - forEach(): List-এর প্রতিটি উপাদানের ওপর নির্দিষ্ট কাজ করে।
  - Callback Function: অন্য একটি ফাংশনে আর্গুমেন্ট হিসেবে
    পাঠানো ফাংশনকে Callback Function বলা হয়।

  এই ধরনের ফাংশন তখন ব্যবহার করা হয়, যখন কোনো কাজের জন্য
  ছোট একটি ফাংশন তৈরি করতে হয়, কিন্তু আলাদা করে ফাংশনের
  নাম দেওয়ার প্রয়োজন হয় না।
*/
}